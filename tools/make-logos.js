'use strict';

// Regenerates renderer/logos.js from the simple-icons package (CC0 brand glyphs).
//   npm run logos
// Only services in the catalog are included. Brands simple-icons doesn't carry
// (e.g. Slack, LinkedIn) fall back to the site's favicon at runtime.

const fs = require('fs');
const path = require('path');
const icons = require('simple-icons');
const { CATALOG } = require('../renderer/catalog.js');

// catalog type -> simple-icons slug, where they differ
const SLUG = { messenger: 'messenger', x: 'x', googlechat: 'googlechat' };

const out = {};
for (const c of CATALOG) {
  const slug = SLUG[c.type] || c.type;
  const key = 'si' + slug.charAt(0).toUpperCase() + slug.slice(1);
  const icon = icons[key];
  if (!icon) { console.log(`  no logo for ${c.type} (${slug}) — favicon fallback`); continue; }
  out[c.type] = { title: icon.title, path: icon.path };
}

const body = `'use strict';

// GENERATED by tools/make-logos.js from simple-icons@${JSON.parse(fs.readFileSync(path.join(path.dirname(require.resolve('simple-icons')), 'package.json'), 'utf8')).version} (CC0-1.0).
// Brand names and logos are trademarks of their respective owners; they're used
// here only to identify each service. Do not edit by hand — run \`npm run logos\`.

const LOGOS = ${JSON.stringify(out, null, 2)};

if (typeof module !== 'undefined') module.exports = { LOGOS };
`;
fs.writeFileSync(path.join(__dirname, '..', 'renderer', 'logos.js'), body);
console.log(`wrote ${Object.keys(out).length} logos: ${Object.keys(out).join(', ')}`);
